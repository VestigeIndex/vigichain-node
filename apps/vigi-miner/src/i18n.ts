/**
 * Vigi Miner's interface, in every language vigichain.org speaks.
 *
 * WHAT WAS WRONG WITH THE PREVIOUS VERSION, and why the types below look the way they do: the app
 * advertised seven languages and shipped one. English had 86 strings; German had 10, French 9,
 * Portuguese 10, Arabic and Chinese 21, Spanish 60. Every missing key fell through to English at
 * runtime, so a German operator opened Mission Control and read a German menu over an English
 * application — the worst of both, and invisible to anyone testing in English.
 *
 * Two changes stop that from coming back:
 *
 *  1. `Dictionary` is `Record<keyof typeof en, string>`, so a locale missing a single key is a
 *     COMPILE ERROR rather than a silent fallback. `npm run build` runs `tsc` first; an incomplete
 *     translation now fails the build the way an incomplete page fails the website's.
 *  2. The locale list matches the ten languages vigichain.org ships, plus Portuguese and Chinese
 *     which this app had already promised. An operator who reads the site in Japanese and then
 *     opens the miner in English has been handed two products.
 *
 * The strings are written per language rather than translated word by word: "Compute envelope" is
 * not "sobre de cómputo", and a power profile called "Eco" keeps its name where the word is
 * already in use.
 */

