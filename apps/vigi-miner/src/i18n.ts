/**
 * The reader's language: an explicit choice first, then the system's, then English.
 *
 * The stored value is validated rather than trusted — a locale that was removed from a later
 * version must not leave the interface blank.
 */
export function detectLocale(): Locale {
  const stored = localStorage.getItem('vigi-miner-locale') as Locale | null
  if (stored && supportedLocales.includes(stored)) return stored
  const base = navigator.language.toLowerCase().split('-')[0] as Locale
  return supportedLocales.includes(base) ? base : 'en'
}

/**
 * Look a string up in the reader's language.
 *
 * There is deliberately no English fallback in the DATA: `Dictionary` makes a missing key a
 * compile error, so a fallback here would only ever hide a bug that cannot occur. The `?? key`
 * remains as the last resort for a key that does not exist at all, which is a programming mistake
 * and should be visible as one.
 */
export function translator(locale: Locale) {
  const dictionary = dictionaries[locale] ?? en
  return (key: string) => (dictionary as Record<string, string>)[key] ?? key
}

/** Does this language read right to left? The shell sets `dir` from this. */
export function isRtl(locale: Locale): boolean {
  return rtlLocales.includes(locale)
}
